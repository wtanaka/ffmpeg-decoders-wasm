//! Generates `ffmpeg_decoders_bindings.rs`: Rust declarations of the FFmpeg
//! structs, constants and functions that users of the module need, with the
//! wasm32-unknown-emscripten layout, from the FFmpeg headers the module was
//! built from. The declarations are not hand-written. The module's exports and
//! these bindings derive from one list, `FFMPEG_FUNCTIONS` in scripts/flags.sh.
//!
//! Usage: gen-bindings <ffmpeg-source-dir> <sysroot-include-dir> <output-file>
//! <ffmpeg-version> "<function>..."
//!
//! Requires libclang at run time (bindgen loads it).

use std::error::Error;
use std::path::Path;
use std::{env, fs};

/// The headers the declarations are generated from.
const WRAPPER: &str = "\
#include <libavcodec/avcodec.h>
#include <libavutil/error.h>
#include <libavutil/frame.h>
#include <libavutil/mem.h>
#include <libavutil/pixfmt.h>
#include <libavutil/version.h>
";

const TARGET: &str = "wasm32-unknown-emscripten";

/// Types declared in addition to those the functions refer to.
const TYPES: [&str; 8] = [
    "AVCodec",
    "AVCodecContext",
    "AVCodecParameters",
    "AVPacket",
    "AVFrame",
    "AVCodecID",
    "AVMediaType",
    "AVPixelFormat",
];

/// Constants declared.
const VARS: &str =
    "^(AV_INPUT_BUFFER_PADDING_SIZE|LIBAV(CODEC|UTIL)_VERSION_(MAJOR|MINOR))$";

/// The comment at the top of the output: what the file declares, and its
/// licence.
fn header(version: &str) -> String {
    format!(
        "\
// Rust declarations of FFmpeg {version}: the structs, constants and functions
// used by callers of hevc-decoder.wasm, with the wasm32-unknown-emscripten
// layout. They match only the module released with this file.
//
// Generated by crates/gen-bindings from the FFmpeg headers the module was built
// from. Derived from those headers, which are licensed LGPL-2.1-or-later
// (FFmpeg-LGPL-2.1.txt).

"
    )
}

/// Generates the declarations: the types and constants for the wasm32 target,
/// compiled against the FFmpeg source and the Emscripten sysroot, then the
/// functions. bindgen emits no functions for WebAssembly targets, so a second
/// pass for the host generates them. Their signatures use only `int`, `size_t`
/// and pointers, which have the same Rust types on wasm32 and on the host; they
/// name the structs of the first pass without defining them.
fn generate(
    source: &Path,
    sysroot: &Path,
    functions: &str,
) -> Result<String, Box<dyn Error>> {
    let names: Vec<&str> = functions.split_whitespace().collect();
    let layout = bindgen::Builder::default()
        .header_contents("ffmpeg-decoders-wrapper.h", WRAPPER)
        .clang_arg(format!("--target={TARGET}"))
        .clang_arg(format!("-I{}", source.display()))
        .clang_arg(format!("-isystem{}", sysroot.display()))
        .allowlist_type(format!("^({})$", TYPES.join("|")))
        .allowlist_var(VARS)
        .default_enum_style(bindgen::EnumVariation::ModuleConsts)
        .layout_tests(false)
        .generate_comments(false)
        .generate()?;
    let calls = bindgen::Builder::default()
        .header_contents("ffmpeg-decoders-wrapper.h", WRAPPER)
        .clang_arg(format!("-I{}", source.display()))
        .allowlist_function(format!("^({})$", names.join("|")))
        .allowlist_recursively(false)
        .default_enum_style(bindgen::EnumVariation::ModuleConsts)
        .layout_tests(false)
        .generate_comments(false)
        .generate()?;
    Ok(format!("{layout}\n{calls}"))
}

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<String> = env::args().skip(1).collect();
    let [source, sysroot, output, version, functions] = args.as_slice() else {
        return Err(
            "usage: gen-bindings <ffmpeg-source-dir> <sysroot-include-dir> \
             <output-file> <ffmpeg-version> \"<function>...\""
                .into(),
        );
    };
    let body = generate(Path::new(source), Path::new(sysroot), functions)?;
    fs::write(output, header(version) + &body)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::header;

    #[test]
    fn the_header_names_the_version_and_the_licence() {
        let text = header("7.1.1");
        assert!(text.contains("FFmpeg 7.1.1"), "{text}");
        assert!(text.contains("LGPL-2.1-or-later"), "{text}");
        assert!(text.lines().all(|line| line.len() <= 80), "{text}");
    }
}
